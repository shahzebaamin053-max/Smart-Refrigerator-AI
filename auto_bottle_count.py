if not all(name in globals() for name in
           ["roi_x1", "roi_y1", "roi_x2", "roi_y2"]):
    raise ValueError("Run Phase 5 first. ROI coordinates not found.")

# Read rectangular ROI coordinates
ROI_X1 = int(roi_x1)
ROI_Y1 = int(roi_y1)
ROI_X2 = int(roi_x2)
ROI_Y2 = int(roi_y2)

# Validate ROI coordinates
if ROI_X1 >= ROI_X2 or ROI_Y1 >= ROI_Y2:
    raise ValueError("Invalid ROI coordinates. Check Phase 5.")

# Counting configuration
MAX_FRAME_GAP = 30

print("RECTANGULAR ROI")
print("Left:", ROI_X1)
print("Top:", ROI_Y1)
print("Right:", ROI_X2)
print("Bottom:", ROI_Y2)

# ============================================
# 3. INITIALIZE TRACKING VARIABLES
# ============================================

# Store the last confirmed position of each bottle
previous_positions = {}

# Store unique tracking IDs
tracking_ids = set()

# Store bottle crossing events
crossing_events = []

# Initialize counters
entry_count = 0
exit_count = 0

# Open uploaded video
cap = cv2.VideoCapture(video_path)

if not cap.isOpened():
    raise ValueError("Could not open uploaded video.")

total_frames = int(cap.get(cv2.CAP_PROP_FRAME_COUNT))

# ============================================
# 4. CENTER POINT ROI STATUS FUNCTION
# ============================================

def get_roi_status(box):

    x_min, y_min, x_max, y_max = map(float, box)

    # Calculate bottle bounding box center
    center_x = (x_min + x_max) / 2
    center_y = (y_min + y_max) / 2

    # Check whether center is inside rectangle
    if (
        ROI_X1 <= center_x <= ROI_X2 and
        ROI_Y1 <= center_y <= ROI_Y2
    ):
        return "INSIDE"

    return "OUTSIDE"


# ============================================
# 5. VIDEO PROCESSING
# ============================================

frame_number = 0
last_annotated_frame = None

while cap.isOpened():

    success, frame = cap.read()

    if not success:
        break

    # YOLO detection and ByteTrack tracking
    results = model.track(
        source=frame,
        persist=True,
        tracker="bytetrack.yaml",
        conf=0.15,
        classes=[39],
        device=device,
        verbose=False
    )

    result = results[0]

    # Create annotated frame
    annotated_frame = result.plot()

    # Draw rectangular ROI
    cv2.rectangle(
        annotated_frame,
        (ROI_X1, ROI_Y1),
        (ROI_X2, ROI_Y2),
        (255, 0, 0),
        3
    )

    cv2.putText(
        annotated_frame,
        "FRIDGE DETECTION ZONE",
        (ROI_X1, max(25, ROI_Y1 - 10)),
        cv2.FONT_HERSHEY_SIMPLEX,
        0.7,
        (255, 0, 0),
        2
    )

    # ========================================
    # 6. PROCESS DETECTED BOTTLES
    # ========================================

    if (
        result.boxes is not None
        and result.boxes.id is not None
    ):

        # Get tracking IDs and bounding boxes
        ids = result.boxes.id.int().cpu().tolist()
        boxes = result.boxes.xyxy.cpu().tolist()

        for track_id, box in zip(ids, boxes):

            tracking_ids.add(track_id)

            # Calculate bottle center
            x_min, y_min, x_max, y_max = map(int, box)

            center_x = int((x_min + x_max) / 2)
            center_y = int((y_min + y_max) / 2)

            # Determine current ROI position
            current_status = get_roi_status(box)

            # --------------------------------
            # INITIALIZE NEW TRACKING ID
            # --------------------------------

            if track_id not in previous_positions:

                # Save initial position.
                # Initially inside bottles are baseline inventory.
                previous_positions[track_id] = {
                    "anchor_status": current_status,
                    "last_frame": frame_number
                }

                continue

            # --------------------------------
            # RETRIEVE TRACKING HISTORY
            # --------------------------------

            history = previous_positions[track_id]

            anchor = history["anchor_status"]

            frame_gap = frame_number - history["last_frame"]

            # --------------------------------
            # CHECK TRACKING GAP
            # --------------------------------

            if frame_gap > MAX_FRAME_GAP:

                # Avoid counting an uncertain transition
                history["anchor_status"] = current_status
                history["last_frame"] = frame_number

                continue

            # --------------------------------
            # DIRECTIONAL COUNTING
            # --------------------------------

            # OUTSIDE -> INSIDE = ENTRY (+1)
            if (
                anchor == "OUTSIDE"
                and current_status == "INSIDE"
            ):

                entry_count += 1

                crossing_events.append({
                    "Frame": frame_number,
                    "Tracking_ID": track_id,
                    "Event": "ENTRY",
                    "Quantity_Change": 1
                })

                print(
                    f"ENTRY | ID: {track_id} | "
                    f"Frame: {frame_number} | "
                    f"Inventory: +1"
                )

            # INSIDE -> OUTSIDE = EXIT (-1)
            elif (
                anchor == "INSIDE"
                and current_status == "OUTSIDE"
            ):

                exit_count += 1

                crossing_events.append({
                    "Frame": frame_number,
                    "Tracking_ID": track_id,
                    "Event": "EXIT",
                    "Quantity_Change": -1
                })

                print(
                    f"EXIT | ID: {track_id} | "
                    f"Frame: {frame_number} | "
                    f"Inventory: -1"
                )

            # --------------------------------
            # UPDATE TRACKING HISTORY
            # --------------------------------

            # Update only after checking the transition
            history["anchor_status"] = current_status
            history["last_frame"] = frame_number

            # --------------------------------
            # DISPLAY BOTTLE CENTER AND STATUS
            # --------------------------------

            # Draw center point
            cv2.circle(
                annotated_frame,
                (center_x, center_y),
                5,
                (0, 255, 255),
                -1
            )

            # Display tracking ID and position
            cv2.putText(
                annotated_frame,
                f"ID:{track_id} {current_status}",
                (x_min, max(20, y_min - 10)),
                cv2.FONT_HERSHEY_SIMPLEX,
                0.5,
                (0, 255, 255),
                2
            )

    # ========================================
    # 7. DISPLAY LIVE COUNTERS
    # ========================================

    net_inventory_change = entry_count - exit_count

    cv2.putText(
        annotated_frame,
        f"Entries (+): {entry_count}",
        (30, 40),
        cv2.FONT_HERSHEY_SIMPLEX,
        0.8,
        (0, 255, 0),
        2
    )

    cv2.putText(
        annotated_frame,
        f"Exits (-): {exit_count}",
        (30, 75),
        cv2.FONT_HERSHEY_SIMPLEX,
        0.8,
        (0, 0, 255),
        2
    )

    cv2.putText(
        annotated_frame,
        f"Net Change: {net_inventory_change}",
        (30, 110),
        cv2.FONT_HERSHEY_SIMPLEX,
        0.8,
        (255, 255, 0),
        2
    )

    last_annotated_frame = annotated_frame

    frame_number += 1


# ============================================
