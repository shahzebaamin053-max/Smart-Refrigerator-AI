def get_roi_status(box):

    x_min, y_min, x_max, y_max = map(int, box)

    # Completely inside the rectangular ROI
    if (
        x_min >= ROI_X1 and
        y_min >= ROI_Y1 and
        x_max <= ROI_X2 and
        y_max <= ROI_Y2
    ):
        return "INSIDE"

    # Completely outside the rectangular ROI
    if (
        x_max < ROI_X1 or
        x_min > ROI_X2 or
        y_max < ROI_Y1 or
        y_min > ROI_Y2
    ):
        return "OUTSIDE"

    # Partially overlapping the ROI
    return "PARTIAL"


# ============================================
# 5. CALCULATE ROI OVERLAP RATIO
# ============================================

def get_overlap_ratio(box):

    x_min, y_min, x_max, y_max = map(float, box)

    # Calculate bottle bounding box area
    box_area = max(0, x_max - x_min) * max(0, y_max - y_min)

    if box_area == 0:
        return 0.0

    # Calculate intersection with rectangular ROI
    ix1 = max(x_min, ROI_X1)
    iy1 = max(y_min, ROI_Y1)
    ix2 = min(x_max, ROI_X2)
    iy2 = min(y_max, ROI_Y2)

    intersection = (
        max(0, ix2 - ix1) *
        max(0, iy2 - iy1)
    )

    return intersection / box_area


