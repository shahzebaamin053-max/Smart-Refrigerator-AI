import pandas as pd

# 1. Ask the user to enter the initial bottle inventory.
starting_inventory = int(input("Enter starting bottle inventory: "))

# 2. Validate the starting inventory.
if starting_inventory < 0:
    raise ValueError("Starting inventory cannot be negative.")

# 3. Check that Phase 6 generated the required event data.
required_columns = ["Frame", "Tracking_ID", "Event", "Quantity_Change"]

if not all(column in events_df.columns for column in required_columns):
    raise ValueError("Phase 6 events_df is missing required columns.")

# 4. Initialize the current inventory.
current_inventory = starting_inventory

# 5. Create a list to store inventory transaction history.
inventory_history = []

# 6. Process every entry and exit event from Phase 6.
for _, event in events_df.iterrows():

    # Read the event information.
    frame = event["Frame"]
    tracking_id = event["Tracking_ID"]
    event_type = str(event["Event"]).strip().upper()

    # Save inventory before the transaction.
    inventory_before = current_inventory

    # Increase inventory when a bottle enters.
    if event_type == "ENTRY":
        current_inventory += 1

    # Decrease inventory when a bottle exits.
    elif event_type == "EXIT":
        if current_inventory > 0:
            current_inventory -= 1
        else:
            print(f"Warning: Inventory is already zero at frame {frame}.")

    # Reject unexpected event labels.
    else:
        print(f"Unknown event '{event_type}' at frame {frame}.")
        continue

    # Store the updated inventory transaction.
    inventory_history.append({
        "Frame": frame,
        "Tracking_ID": tracking_id,
        "Event": event_type,
        "Inventory_Before": inventory_before,
        "Inventory_After": current_inventory
    })

# 7. Convert transaction history into a DataFrame.
inventory_history_df = pd.DataFrame(
    inventory_history,
    columns=[
        "Frame",
        "Tracking_ID",
        "Event",
        "Inventory_Before",
        "Inventory_After"
    ]
)

# 8. Calculate total inventory changes.
total_entries = sum(
    1 for event in inventory_history if event["Event"] == "ENTRY"
)

total_exits = sum(
    1 for event in inventory_history if event["Event"] == "EXIT"
)

# 9. Display the final inventory report.
print("\n========== PHASE 7: INVENTORY REPORT ==========")

print("Starting Inventory:", starting_inventory)
print("Total Entries:", total_entries)
print("Total Exits:", total_exits)
print("Net Inventory Change:", current_inventory - starting_inventory)
print("Final Inventory:", current_inventory)

# 10. Display transaction history.
print("\n========== INVENTORY TRANSACTION HISTORY ==========")

if not inventory_history_df.empty:
    display(inventory_history_df)
else:
    print("No bottle entry or exit events detected.")

print("\nPHASE 7 INVENTORY MANAGEMENT COMPLETED!")

